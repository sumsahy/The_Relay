"""Compute Tables 2a, 2b and 3 from results.csv only (the brief: every figure must be computable from it).

Definitions (state these in the write-up):
- Time is measured from the request's arrival, so queue waiting is included.
- first_token_ms = when the VERIFIED answer starts reaching the person (we never stream unverified text).
- Percentiles: nearest-rank. First token over requests that got an answer or refusal (status ok);
  total time over the same requests.
- Succeeded = status ok (answered, reduced answer, or correct refusal). Timed out or given up = status timeout.
- Peak queue length: max number of requests that had arrived but not yet started work, rebuilt from
  start_time + queue_wait_ms.
Run: python scripts/make_tables.py   -> results/tables.md
"""
import csv
import math
from collections import defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
rows = list(csv.DictReader(open(ROOT / "results.csv")))
# Groq on-demand price for gpt-oss-20b, USD per 1M tokens (input, output). Free tier costs $0; this is what the
# same tokens would cost on the paid plan: $0.075 in / $0.30 out per 1M (Groq console via developersdigest.tech, 2026-10).
PRICE_IN, PRICE_OUT = 0.075, 0.30


def pct(xs, p):
    xs = sorted(xs)
    if not xs:
        return None
    return xs[max(0, math.ceil(p / 100 * len(xs)) - 1)]


def fmt3(xs):
    v = [pct(xs, p) for p in (50, 95, 99)]
    return "not measured" if v[0] is None else " / ".join(f"{x:.0f}" for x in v)


def t(r):
    return datetime.fromisoformat(r["start_time"]).timestamp()


def peak_queue(rs):
    ev = []
    for r in rs:
        q = float(r.get("queue_wait_ms") or 0)
        if q > 0:
            ev += [(t(r), 1), (t(r) + q / 1000, -1)]
    cur = best = 0
    for _, d in sorted(ev):
        cur += d
        best = max(best, cur)
    return best


by = defaultdict(list)
for r in rows:
    by[(r["scenario"], r["source"])].append(r)

out = ["# Results tables (generated by scripts/make_tables.py from results.csv)\n"]
out.append("## Table 2a: Latency, one row per load scenario\n")
out.append("| Scenario | Real or stand-in | Requests sent | Duration (s) | Offered rate (per min) | First token p50 / p95 / p99 (ms) | Total time p50 / p95 / p99 (ms) |")
out.append("|---|---|---|---|---|---|---|")
order = ["quality", "manual", "steady", "burst", "burst_naive", "overload", "halved", "daily"]
keys = sorted(by, key=lambda k: (order.index(k[0]) if k[0] in order else 99, k[1]))
b_rows = []
for k in keys:
    rs = by[k]
    starts = [t(r) for r in rs]
    ends = [t(r) + float(r["total_ms"] or 0) / 1000 for r in rs]
    dur = max(ends) - min(starts)
    span = max(starts) - min(starts)
    offered = len(rs) / (span / 60) if span > 0 else float("nan")
    ok = [r for r in rs if r["status"] == "ok"]
    ft = [float(r["first_token_ms"]) for r in ok if r["first_token_ms"]]
    tt = [float(r["total_ms"]) for r in ok]
    out.append(f"| {k[0]} | {k[1]} | {len(rs)} | {dur:.0f} | {offered:.1f} | {fmt3(ft)} | {fmt3(tt)} |")
    n = len(rs)
    share = lambda s: 100 * sum(r["status"] == s for r in rs) / n
    answered = [r for r in ok if r["outcome"] in ("answered", "answered_reduced")]
    tok = [int(r["tokens_in"]) + int(r["tokens_out"]) for r in answered]
    cost = (sum(int(r["tokens_in"]) for r in rs) * PRICE_IN + sum(int(r["tokens_out"]) for r in rs) * PRICE_OUT) / 1e6
    per1000 = 1000 * cost / len(answered) if answered else float("nan")
    b_rows.append(f"| {k[0]} | {share('ok'):.1f} | {share('rate_limited'):.1f} | {share('timeout'):.1f} "
                  f"| {sum(int(r['retries']) for r in rs) / n:.2f} | {peak_queue(rs)} | "
                  f"{(sum(tok) / len(tok)) if tok else float('nan'):.0f} | ${per1000:.2f} (free tier: $0) |")

out.append("\n## Table 2b: Outcomes, same rows\n")
out.append("| Scenario | Succeeded % | Rate-limited % | Timed out or given up % | Retries per request | Peak queue length | Tokens per answer | Cost per 1,000 answers |")
out.append("|---|---|---|---|---|---|---|---|")
out += b_rows
errs = {k[0]: 100 * sum(r["status"] == "error" for r in by[k]) / len(by[k]) for k in keys}
out.append("\nErrors (status=error, not in the brief's columns): " +
           ", ".join(f"{k} {v:.1f}%" for k, v in errs.items()))

out.append("\n## Table 3: Retrieval settings (real Groq, scenario 'quality')\n")
out.append("| Setting (piece size, pieces fetched, re-rank) | Questions asked | Correct and cited % | Wrong % | Correctly refused % | Tokens per answer | First token p50 / p95 (ms) | Total time p50 / p95 (ms) |")
out.append("|---|---|---|---|---|---|---|---|")
q = [r for r in rows if r["scenario"] == "quality" and r["source"] == "real"]
CHOSEN = "section-300/k5/hybrid/no-rerank"
qid = lambda r: r["request_id"].rsplit("-", 1)[-1]
others = [r for r in q if r["retrieval_setting"] != CHOSEN]
subset = sorted({qid(r) for r in others})
groups = []
for setting in sorted({r["retrieval_setting"] for r in q}, key=lambda x: x != CHOSEN):
    rs = [r for r in q if r["retrieval_setting"] == setting]
    groups.append((setting + (" (all questions)" if setting == CHOSEN and others else ""), rs))
    if setting == CHOSEN and others:
        # like-for-like: the chosen setting on exactly the questions the other settings were asked
        groups.append((setting + f" (same {len(subset)} as below)", [r for r in rs if qid(r) in subset]))
notes = []
for name, rs in groups:
    graded = [r for r in rs if r["answer_grade"]]
    g = lambda x: 100 * sum(r["answer_grade"] == x for r in graded) / len(graded) if graded else float("nan")
    tok = [int(r["tokens_in"]) + int(r["tokens_out"]) for r in rs]
    ft = [float(r["first_token_ms"]) for r in rs if r["first_token_ms"]]
    tt = [float(r["total_ms"]) for r in rs]
    p2 = lambda xs: "not measured" if not xs else f"{pct(xs, 50):.0f} / {pct(xs, 95):.0f}"
    out.append(f"| {name} | {len(rs)} ({len(graded)} graded) | {g('correct'):.1f} | {g('wrong'):.1f} | "
               f"{g('refused_correctly'):.1f} | {sum(tok) / len(tok):.0f} | {p2(ft)} | {p2(tt)} |")
    notes.append(f"- {name}: refused wrongly {g('refused_wrongly'):.1f}% "
                 f"({sum(r['answer_grade'] == 'refused_wrongly' for r in graded)} of {len(graded)})")
out.append(f"\nSubset asked of every setting: {', '.join(subset)}. Compare settings on the 'same' rows only.")
out.append("The brief's columns leave out wrongly refused answers; they are the remainder:")
out += notes
(ROOT / "results" / "tables.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
